// Builds src/features/cook/nutrition-seed.ts from USDA FoodData Central (public domain, CC0 1.0).
//
//   node scripts/nutrition-import/build.mjs <Foundation Foods CSV folder> <SR Legacy CSV folder>
//
// Downloads (about 3.5 MB and 6.7 MB):
//   https://fdc.nal.usda.gov/fdc-datasets/FoodData_Central_foundation_food_csv_2025-12-18.zip
//   https://fdc.nal.usda.gov/fdc-datasets/FoodData_Central_sr_legacy_food_csv_2018-04.zip
//
// foods.json lists the curated foods: our name, the FoodData Central id, and optionally
//   "piece": the start of a portion label whose gram weight is one piece (e.g. "large" for an egg)
//   "ml":    true for liquids; per 100 ml is worked out from the dataset's own weight of one cup (236.588 ml)
// Nothing is estimated: a number is either read from the dataset or derived from its portion weights.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { loadFoods } from "./fdc.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const [foundationDir, srDir] = process.argv.slice(2);
if (!foundationDir || !srDir) {
  console.error("usage: node scripts/nutrition-import/build.mjs <Foundation Foods folder> <SR Legacy folder>");
  process.exit(1);
}
const data = { foundation: loadFoods(foundationDir), sr: loadFoods(srDir) };
const label = { foundation: "Foundation Foods 2025-12", sr: "SR Legacy 2018-04" };
const CUP_ML = 236.588;
const round = (n) => Math.round(n * 10) / 10;
const fail = (msg) => {
  console.error(msg);
  process.exit(1);
};

const rows = [];
for (const f of JSON.parse(readFileSync(join(here, "foods.json"), "utf8"))) {
  const food = data[f.dataset]?.get(f.fdc);
  if (!food) fail(`${f.name}: FoodData Central id ${f.fdc} not found in ${f.dataset}`);
  if (food.kcal === undefined || food.protein === undefined) fail(`${f.name}: ${f.fdc} has no energy or protein`);
  const source = `USDA FoodData Central ${label[f.dataset]}, ${f.fdc}: ${food.description}`;
  rows.push({ name: f.name, basis: "100g", kcal: round(food.kcal), protein_g: round(food.protein), source });
  if (f.ml) {
    const cup = food.portions.find((p) => p.label === "cup");
    if (!cup) fail(`${f.name}: no "cup" portion to derive per 100 ml`);
    const gramsPerMl = cup.grams / CUP_ML;
    rows.push({
      name: f.name,
      basis: "100ml",
      kcal: round(food.kcal * gramsPerMl),
      protein_g: round(food.protein * gramsPerMl),
      source: `${source}; 1 cup = ${round(cup.grams)} g`,
    });
  }
  if (f.piece) {
    const portion = food.portions.find((p) => p.label.startsWith(f.piece));
    if (!portion) fail(`${f.name}: no portion starting with "${f.piece}" (have: ${food.portions.map((p) => p.label).join(", ")})`);
    rows.push({
      name: f.name,
      basis: "piece",
      kcal: round((food.kcal * portion.grams) / 100),
      protein_g: round((food.protein * portion.grams) / 100),
      source: `${source}; 1 ${portion.label} = ${round(portion.grams)} g`,
    });
  }
}

const out = `// Generated by scripts/nutrition-import/build.mjs from USDA FoodData Central (public domain, CC0 1.0). Do not edit by hand.
// Energy and protein per 100 g, per 100 ml (derived from the dataset's weight of one cup) or per piece (derived from
// the dataset's portion weight). Each row names the exact record it came from.
import type { NutritionBasis } from "./nutrition";

export type SeedRow = { name: string; basis: NutritionBasis; kcal: number; protein_g: number; source: string };

export const NUTRITION_SEED: readonly SeedRow[] = ${JSON.stringify(rows, null, 2)};
`;
writeFileSync(join(here, "../../src/features/cook/nutrition-seed.ts"), out);
console.log(`Wrote ${rows.length} rows for ${new Set(rows.map((r) => r.name)).size} foods.`);

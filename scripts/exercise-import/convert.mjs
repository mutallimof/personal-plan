// Converts free-exercise-db (Unlicense) into idempotent SQL for the `exercises` table.
//
//   node scripts/exercise-import/convert.mjs
//
// Reads  scripts/exercise-import/free-exercise-db.json
// Writes scripts/exercise-import/sql/exercises-import.sql        (everything, one transaction)
//        scripts/exercise-import/sql/parts/exercises-NN.sql       (same data in smaller chunks)
//        scripts/exercise-import/sql/report.json                  (counts + unmatched list)
//
// Data only: INSERT ... ON CONFLICT (slug) DO NOTHING, plus a name check so exercises we already have
// (even with different punctuation / capitalisation) are not inserted again. No schema changes.

import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import {
  ALREADY_HAVE,
  EQUIPMENT_MAP,
  EXISTING_NAMES,
  FAMILY_NOISE,
  FAMILY_RULES,
  GROUP_MAP,
  MUSCLE_MAP,
  shoulderIds,
} from "./mappings.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const source = JSON.parse(readFileSync(join(here, "free-exercise-db.json"), "utf8"));
const CHUNK = 150;
const root = join(here, "..", "..");

const kebab = (s) =>
  s
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");

function familyOf(e) {
  const n = e.name.toLowerCase();
  for (const [re, fam] of FAMILY_RULES) if (re.test(n)) return fam;
  if (e.category === "stretching") return "stretch";
  if (e.category === "cardio") return "cardio";
  const words = kebab(e.name)
    .split("-")
    .filter((w) => w && !FAMILY_NOISE.has(w));
  return words.slice(0, 3).join("-") || kebab(e.name);
}

function musclesOf(e, list) {
  const out = [];
  for (const m of list) {
    const ids = m === "shoulders" ? shoulderIds(e.name) : (MUSCLE_MAP[m] ?? []);
    for (const id of ids) if (!out.includes(id)) out.push(id);
  }
  return out;
}

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const arr = (a) => (a.length ? `ARRAY[${a.map(q).join(",")}]::text[]` : "ARRAY[]::text[]");

// slug -> source id for every dataset exercise that has pictures and a row in our table (new or already ours).
const imageIds = {};
const addImage = (slug, e) => {
  if (e.images?.length) imageIds[slug] = e.id;
};
// Hand-seeded rows in setup.sql (before the import block): normalised name -> slug.
const seedSlugByName = {};
{
  const sql = readFileSync(join(root, "setup.sql"), "utf8").split("-- ===== exercise import")[0];
  for (const m of sql.matchAll(/^\('([a-z0-9-]+)','([^']*)'/gm)) {
    seedSlugByName[m[2].toLowerCase().replace(/[^a-z0-9]/g, "")] = m[1];
  }
}
const seenSlugs = new Set();
const norm = (s) => s.toLowerCase().replace(/[^a-z0-9]/g, "");
const existingNames = new Set(EXISTING_NAMES.map(norm));
const seenNames = new Set();
const rows = [];
const skipped = { alreadyHave: [], sameNameAsExisting: [], duplicateInDataset: [] };
const noMuscleMatch = [];
const byFamily = {};

for (const e of source) {
  if (e.name in ALREADY_HAVE) {
    skipped.alreadyHave.push(`${e.name} -> ${ALREADY_HAVE[e.name]}`);
    addImage(ALREADY_HAVE[e.name], e);
    continue;
  }
  const normName = norm(e.name);
  if (existingNames.has(normName)) {
    skipped.sameNameAsExisting.push(e.name);
    if (seedSlugByName[normName]) addImage(seedSlugByName[normName], e);
    continue;
  }
  if (seenNames.has(normName)) {
    skipped.duplicateInDataset.push(e.name);
    continue;
  }
  seenNames.add(normName);

  let slug = kebab(e.name);
  for (let i = 2; seenSlugs.has(slug); i++) slug = `${kebab(e.name)}-${i}`;
  seenSlugs.add(slug);
  addImage(slug, e);

  const primary = musclesOf(e, e.primaryMuscles);
  const secondary = musclesOf(e, e.secondaryMuscles).filter((m) => !primary.includes(m));
  if (!primary.length) noMuscleMatch.push(e.name);

  const first = e.primaryMuscles[0];
  const group = (first && GROUP_MAP[first]) || "core";
  const equipment = EQUIPMENT_MAP[e.equipment ?? "other"] ?? "other";
  const family = familyOf(e);
  byFamily[family] = (byFamily[family] ?? 0) + 1;

  rows.push(
    `(${q(slug)},${q(e.name)},${q(family)},${q(equipment)},${q(group)},${arr(primary)},${arr(secondary)},${arr(e.instructions ?? [])})`,
  );
}

const header = (extra) => `-- free-exercise-db import (https://github.com/yuhonas/free-exercise-db, Unlicense / public domain).
-- Generated by scripts/exercise-import/convert.mjs. Data only; safe to run more than once.
-- Existing rows are never changed: conflicts on slug are ignored, and any exercise whose name already exists
-- (ignoring case and punctuation) is skipped.${extra}
`;

const statement = (chunk) => `INSERT INTO public.exercises (slug, name, family, equipment, muscle_group, primary_muscles, secondary_muscles, steps)
SELECT v.slug, v.name, v.family, v.equipment, v.muscle_group, v.primary_muscles, v.secondary_muscles, v.steps
FROM (VALUES
${chunk.join(",\n")}
) AS v(slug, name, family, equipment, muscle_group, primary_muscles, secondary_muscles, steps)
WHERE NOT EXISTS (
  SELECT 1 FROM public.exercises e
  WHERE regexp_replace(lower(e.name), '[^a-z0-9]', '', 'g') = regexp_replace(lower(v.name), '[^a-z0-9]', '', 'g')
)
ON CONFLICT (slug) DO NOTHING;
`;

const chunks = [];
for (let i = 0; i < rows.length; i += CHUNK) chunks.push(rows.slice(i, i + CHUNK));

const out = join(here, "sql");
rmSync(out, { recursive: true, force: true });
mkdirSync(join(out, "parts"), { recursive: true });

writeFileSync(
  join(out, "exercises-import.sql"),
  `${header("\n-- Runs as one transaction.")}\nBEGIN;\n\n${chunks.map(statement).join("\n")}\nCOMMIT;\n`,
);
chunks.forEach((c, i) => {
  const n = String(i + 1).padStart(2, "0");
  writeFileSync(join(out, "parts", `exercises-${n}.sql`), `${header(`\n-- Part ${i + 1} of ${chunks.length}.`)}\n${statement(c)}`);
});

const report = {
  sourceTotal: source.length,
  toInsert: rows.length,
  skippedAlreadyHave: skipped.alreadyHave.length,
  skippedSameNameAsExisting: skipped.sameNameAsExisting.length,
  skippedDuplicateInDataset: skipped.duplicateInDataset.length,
  noMuscleMatchCount: noMuscleMatch.length,
  noMuscleMatch,
  parts: chunks.length,
  families: Object.keys(byFamily).length,
  topFamilies: Object.entries(byFamily)
    .sort((a, b) => b[1] - a[1])
    .slice(0, 25),
  skipped,
};
writeFileSync(join(out, "report.json"), JSON.stringify(report, null, 2));
console.log(JSON.stringify({ ...report, noMuscleMatch: undefined, skipped: undefined, topFamilies: undefined }, null, 2));
console.log("no muscle match:", noMuscleMatch.join("; "));

// Image map for the app: slug -> free-exercise-db id. Images are loaded from the public repo, never copied.
const ids = Object.entries(imageIds).sort(([a], [b]) => a.localeCompare(b));
writeFileSync(
  join(root, "src", "features", "gym", "exercise-images.ts"),
  `// Generated by scripts/exercise-import/convert.mjs. Do not edit by hand.
// exercise slug -> free-exercise-db id (https://github.com/yuhonas/free-exercise-db, Unlicense).
export const EXERCISE_IMAGE_IDS: Record<string, string> = {
${ids.map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n")}
};
`,
);
console.log("image ids:", ids.length);

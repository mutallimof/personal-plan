// Builds setup.sql: every migration in drizzle/migrations (in filename order) followed by the exercise import,
// in ONE transaction. Paste setup.sql into the Supabase SQL editor on an EMPTY project and run it once.
//
//   node scripts/build-setup-sql.mjs

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => readFileSync(join(root, p), "utf8").replace(/\r\n/g, "\n").trim();

const migrations = readdirSync(join(root, "drizzle/migrations"))
  .filter((f) => f.endsWith(".sql"))
  .sort();
// The import file wraps itself in BEGIN/COMMIT; here the whole script is one transaction instead.
const importSql = read("scripts/exercise-import/sql/exercises-import.sql").replace(/^BEGIN;\s*$/m, "").replace(/^COMMIT;\s*$/m, "").trim();

const parts = [
  `-- Lifeplan: full database setup for a NEW, EMPTY Supabase project.
-- Paste into the Supabase SQL editor and run ONCE.
--   1. Schema, row-level security, triggers and functions (drizzle/migrations)
--   2. Starter exercises and the free-exercise-db import (scripts/exercise-import)
-- Everything runs in one transaction: if any statement fails, nothing is applied.
-- Not meant to be re-run: the CREATE TABLE statements fail on a database that already has the tables.
-- Generated by scripts/build-setup-sql.mjs, do not edit by hand.

BEGIN;
`,
  ...migrations.map((f) => `-- ===== migration: ${f} =====\n\n${read(`drizzle/migrations/${f}`)}\n`),
  `-- ===== exercise import (free-exercise-db, Unlicense) =====\n\n${importSql}\n`,
  "COMMIT;\n",
];
writeFileSync(join(root, "setup.sql"), parts.join("\n"));
console.log(`setup.sql written: ${migrations.length} migration(s) + exercise import`);
